test('2D, contour, surface 3D, camera, slider e toggle reali',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/#/dev');
  const scene=page.locator('[data-plot-id="wave-3d"]');
  await expect(scene).toHaveAttribute('data-plot-ready','true');
  await expect(page.locator('[data-plot-id="wave-2d"]')).toHaveAttribute('data-plot-ready','true');
  await expect(page.locator('[data-plot-id="wave-section"]')).toHaveAttribute('data-plot-ready','true');
  await expect(scene.locator('canvas').first()).toBeVisible();
  await page.getByLabel('Zoom avanti Superficie 3D').click();
  await expect(scene).toHaveAttribute('data-camera',/.+/);
  const camera=await scene.getAttribute('data-camera');
  await scene.locator('.js-plotly-plot').evaluate(el=>el.setAttribute('data-instance-check','retained'));
  await page.getByLabel('Ampiezza valore').fill('2');
  await expect(page.getByTestId('probe-value')).toHaveText('2.000');
  await expect.poll(()=>scene.locator('.js-plotly-plot').evaluate((el:any)=>el.data[0].z[16][24])).toBeCloseTo(2);
  await expect(scene.locator('.js-plotly-plot')).toHaveAttribute('data-instance-check','retained');
  expect(await scene.getAttribute('data-camera')).toBe(camera);
  await page.getByLabel('Ampiezza slider').focus();await page.getByLabel('Ampiezza slider').press('ArrowRight');
  await expect(page.getByTestId('probe-value')).toHaveText('2.100');
  const box=await scene.locator('.js-plotly-plot').boundingBox();expect(box).not.toBeNull();
  await page.mouse.move(box!.x+box!.width*.45,box!.y+box!.height*.4);
  await page.mouse.down();await page.mouse.move(box!.x+box!.width*.6,box!.y+box!.height*.5,{steps:12});await page.mouse.up();
  await expect.poll(()=>scene.getAttribute('data-camera')).not.toBe(camera);
  await scene.locator('.camera-toolbar').getByRole('button',{name:'Pan',exact:true}).click();
  const orbitCamera=await scene.getAttribute('data-camera');
  await page.mouse.move(box!.x+box!.width*.45,box!.y+box!.height*.4);
  await page.mouse.down();await page.mouse.move(box!.x+box!.width*.5,box!.y+box!.height*.45,{steps:8});await page.mouse.up();
  await expect.poll(()=>scene.getAttribute('data-camera')).not.toBe(orbitCamera);
  await scene.getByRole('button',{name:'Ripristina camera'}).click();
  await expect.poll(()=>scene.locator('.js-plotly-plot').evaluate((el:any)=>el.layout.scene.camera.eye.x)).toBeCloseTo(1.6);
  await page.screenshot({path:'../Docs/F05_assets/combined-2d-3d.png',fullPage:true});
  await page.getByLabel('Presentazione').selectOption('toggle');
  await expect(page.locator('[data-plot-id="wave-3d"]')).toHaveCount(0);
  await page.getByRole('button',{name:'3D',exact:true}).click();
  await expect(scene).toHaveAttribute('data-plot-ready','true');
  await expect(page.getByTestId('probe-value')).toHaveText('2.100');
  await page.getByLabel('Superficie',{exact:true}).selectOption('mesh');
  await expect.poll(()=>scene.locator('.js-plotly-plot').evaluate((el:any)=>el.data[0].type)).toBe('mesh3d');
  expect(errors).toEqual([]);
});
