import { test, expect } from '@playwright/test';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
const manifest=JSON.parse(readFileSync(new URL('../../Data/introduction_companion_manifest.json',import.meta.url),'utf8'));
test('PDF originale, placeholder, sincronizzazione e limiti',async({page,request})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  const canvas=(n:number)=>page.locator('canvas[data-rendered-page="'+n+'"]');
  await expect(canvas(1)).toBeVisible();
  await expect(page.getByLabel('Companion pagina 1')).toBeVisible();
  const bytes=await (await request.get('/course-assets/'+manifest.source_pdf.filename)).body();
  expect(createHash('sha256').update(bytes).digest('hex')).toBe(manifest.source_pdf.sha256);
  await expect(page.getByRole('button',{name:'Pagina precedente'})).toBeDisabled();
  await page.getByRole('button',{name:'Pagina successiva'}).click();
  await expect(canvas(2)).toBeVisible();await expect(page.getByLabel('Companion pagina 2')).toBeVisible();
  await page.getByRole('button',{name:'Pagina precedente'}).click();await expect(canvas(1)).toBeVisible();
  await page.getByLabel('Numero pagina').fill('12');await page.getByRole('button',{name:'Vai alla pagina'}).click();
  await expect(canvas(12)).toBeVisible();await expect(page.getByLabel('Companion pagina 12')).toBeVisible();
  await page.getByLabel('Numero pagina').fill('100');await page.getByRole('button',{name:'Vai alla pagina'}).click();
  await expect(canvas(36)).toBeVisible();await expect(page.getByRole('button',{name:'Pagina successiva'})).toBeDisabled();
  await page.getByLabel('Numero pagina').fill('0');await page.getByRole('button',{name:'Vai alla pagina'}).click();
  await expect(canvas(1)).toBeVisible();
  await page.screenshot({path:'../Docs/F05_assets/study-shell.png',fullPage:true});
  expect(errors).toEqual([]);
});
